package com.drishyopot.app.yt

enum class AudioKind { ORIGINAL, DUBBED, DESCRIPTIVE, OTHER }

data class YtVideoStream(
    val url: String,
    val height: Int,
    val fps: Int,
    val codec: String?,
    val bitrate: Int,
    val videoOnly: Boolean,
    val width: Int = 0,
    val mimeType: String = "video/mp4",
    val ranges: MediaRanges = MediaRanges(),
    val contentLength: Long = 0,
) {
    val family: String
        get() = when {
            codec == null -> "other"
            codec.startsWith("avc") -> "avc"
            codec.startsWith("vp9") || codec.startsWith("vp09") -> "vp9"
            codec.startsWith("av01") -> "av1"
            codec.startsWith("hev") || codec.startsWith("hvc") -> "hevc"
            else -> "other"
        }
}

data class YtAudioStream(
    val url: String,
    val trackId: String?,
    val label: String,
    val kind: AudioKind,
    val language: String?,
    val bitrate: Int,
    val codec: String?,
    val mimeType: String = "audio/mp4",
    val ranges: MediaRanges = MediaRanges(),
    val contentLength: Long = 0,
)

/** Byte ranges of the init segment and sidx index, needed to describe a stream in a DASH manifest. */
data class MediaRanges(val initStart: Long = 0, val initEnd: Long = 0, val indexStart: Long = 0, val indexEnd: Long = 0) {
    val valid: Boolean get() = initEnd > initStart && indexEnd > indexStart && indexStart > initEnd
}

data class YtSubtitle(
    val url: String,
    val language: String,
    val label: String,
    val mimeType: String,
    val autoGenerated: Boolean,
)

data class YtVideo(
    val id: String,
    val title: String,
    val uploader: String,
    val durationMs: Long,
    val isLive: Boolean,
    val thumbnail: String?,
    val videoOnly: List<YtVideoStream>,
    val muxed: List<YtVideoStream>,
    val audio: List<YtAudioStream>,
    val subtitles: List<YtSubtitle>,
    val hlsUrl: String?,
    val resolvedAt: Long = System.currentTimeMillis(),
    val uploaderAvatar: String? = null,
    val uploaderUrl: String? = null,
    val subscribers: Long = -1,
    val uploadedAtMs: Long = 0,
    val description: String = "",
    val likeCount: Long = -1,
    val viewCount: Long = -1,
    val chapters: List<YtChapter> = emptyList(),
    val related: List<YtRelated> = emptyList(),
) {
    /** The UC… id taken from the channel URL, needed to subscribe. */
    val channelId: String?
        get() = uploaderUrl?.substringAfter("/channel/", "")?.substringBefore('/')?.takeIf { it.startsWith("UC") }

    val hasDubbedAudio: Boolean get() = audio.any { it.kind == AudioKind.DUBBED }
}

data class YtRelated(val id: String, val title: String, val uploader: String, val durationSec: Long, val views: Long, val date: String, val thumbnail: String?)

data class YtChapter(val title: String, val startMs: Long, val preview: String?)

data class YtComment(val author: String, val avatar: String?, val text: String, val likes: Long, val date: String, val pinned: Boolean)

data class YtComments(val disabled: Boolean, val count: Long, val items: List<YtComment>)

data class YtPlaylistItem(val id: String, val title: String, val uploader: String, val durationSec: Long)

data class YtPlaylist(val title: String, val items: List<YtPlaylistItem>, val truncated: Boolean)

/** The user's current stream choices for one video. height 0 = automatic. */
data class StreamChoice(val height: Int = 0, val audioTrackId: String? = null)

class YoutubeException(message: String, val kind: String = "OTHER", cause: Throwable? = null) : Exception(message, cause)
