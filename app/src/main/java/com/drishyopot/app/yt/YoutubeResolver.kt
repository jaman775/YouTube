package com.drishyopot.app.yt

import android.media.MediaCodecList
import com.drishyopot.app.diagnostics.DiagnosticLog
import org.schabi.newpipe.extractor.NewPipe
import org.schabi.newpipe.extractor.Page
import org.schabi.newpipe.extractor.ServiceList
import org.schabi.newpipe.extractor.localization.Localization
import org.schabi.newpipe.extractor.playlist.PlaylistInfo
import org.schabi.newpipe.extractor.stream.AudioStream
import org.schabi.newpipe.extractor.stream.StreamInfo
import org.schabi.newpipe.extractor.stream.StreamType
import java.util.concurrent.ConcurrentHashMap

/** Turns a YouTube video ID into playable stream URLs using NewPipe Extractor. All calls block. */
object YoutubeResolver {
    private const val CACHE_TTL_MS = 4 * 60 * 60 * 1000L
    private const val MAX_PLAYLIST_PAGES = 6
    private val cache = ConcurrentHashMap<String, YtVideo>()
    @Volatile private var initialised = false

    @Synchronized
    private fun ensureInit() {
        if (initialised) return
        NewPipe.init(NewPipeDownloader(), Localization.DEFAULT)
        initialised = true
    }

    fun cached(id: String): YtVideo? = cache[id]?.takeIf { System.currentTimeMillis() - it.resolvedAt < CACHE_TTL_MS }

    fun resolve(id: String, forceRefresh: Boolean = false): YtVideo {
        if (!forceRefresh) cached(id)?.let { return it }
        ensureInit()
        try {
            val info = StreamInfo.getInfo(ServiceList.YouTube, YoutubeUrls.watchUrl(id))
            val video = convert(id, info)
            cache[id] = video
            return video
        } catch (e: Exception) {
            DiagnosticLog.log("Resolver", "Resolve failed for $id", e)
            throw YoutubeException(e.message ?: e.javaClass.simpleName, e)
        }
    }

    private fun convert(id: String, info: StreamInfo): YtVideo {
        val live = info.streamType == StreamType.LIVE_STREAM || info.streamType == StreamType.AUDIO_LIVE_STREAM

        fun rangesOf(item: org.schabi.newpipe.extractor.services.youtube.ItagItem?) = item?.let {
            MediaRanges(it.initStart.toLong(), it.initEnd.toLong(), it.indexStart.toLong(), it.indexEnd.toLong())
        } ?: MediaRanges()

        fun videoStream(s: org.schabi.newpipe.extractor.stream.VideoStream, videoOnly: Boolean) = YtVideoStream(
            url = s.content, height = s.height, fps = s.fps, codec = s.codec,
            bitrate = s.bitrate, videoOnly = videoOnly,
            width = s.width, mimeType = s.format?.mimeType ?: "video/mp4",
            ranges = rangesOf(s.itagItem),
        )

        val audio = info.audioStreams.filter { it.isUrl }.map { a ->
            YtAudioStream(
                url = a.content,
                trackId = a.audioTrackId,
                label = audioLabel(a),
                kind = when (a.audioTrackType) {
                    org.schabi.newpipe.extractor.stream.AudioTrackType.ORIGINAL -> AudioKind.ORIGINAL
                    org.schabi.newpipe.extractor.stream.AudioTrackType.DUBBED -> AudioKind.DUBBED
                    org.schabi.newpipe.extractor.stream.AudioTrackType.DESCRIPTIVE -> AudioKind.DESCRIPTIVE
                    else -> AudioKind.OTHER
                },
                language = a.audioLocale?.toLanguageTag(),
                bitrate = a.averageBitrate,
                codec = a.codec,
                mimeType = a.format?.mimeType ?: "audio/mp4",
                ranges = rangesOf(a.itagItem),
            )
        }
        val subs = info.subtitles.filter { it.isUrl }.map { s ->
            YtSubtitle(
                url = s.content,
                language = s.languageTag ?: "und",
                label = s.displayLanguageName + if (s.isAutoGenerated) " (auto)" else "",
                mimeType = subtitleMime(s.format?.mimeType),
                autoGenerated = s.isAutoGenerated,
            )
        }
        return YtVideo(
            id = id,
            title = info.name.orEmpty(),
            uploader = info.uploaderName.orEmpty(),
            durationMs = info.duration * 1000,
            isLive = live,
            thumbnail = info.thumbnails.firstOrNull()?.url,
            videoOnly = info.videoOnlyStreams.filter { it.isUrl }.map { videoStream(it, true) },
            muxed = info.videoStreams.filter { it.isUrl }.map { videoStream(it, false) },
            audio = audio,
            subtitles = subs,
            hlsUrl = info.hlsUrl?.takeIf { it.isNotBlank() },
        )
    }

    private fun audioLabel(a: AudioStream): String {
        val lang = a.audioLocale?.displayLanguage?.takeIf { it.isNotBlank() }
        val kind = when (a.audioTrackType) {
            org.schabi.newpipe.extractor.stream.AudioTrackType.ORIGINAL -> "original"
            org.schabi.newpipe.extractor.stream.AudioTrackType.DUBBED -> "dubbed"
            org.schabi.newpipe.extractor.stream.AudioTrackType.DESCRIPTIVE -> "descriptive"
            else -> null
        }
        return listOfNotNull(lang ?: a.audioTrackName, kind).joinToString(" · ").ifBlank { "Default" }
    }

    /** ExoPlayer needs a Media3 MIME type for side-loaded subtitles. */
    private fun subtitleMime(mime: String?): String = when {
        mime == null -> "text/vtt"
        mime.contains("vtt", true) -> "text/vtt"
        mime.contains("ttml", true) || mime.contains("xml", true) -> "application/ttml+xml"
        mime.contains("srt", true) || mime.contains("subrip", true) -> "application/x-subrip"
        else -> mime
    }

    /** Loads up to [maxItems] entries of a playlist, following pagination. */
    fun playlist(url: String, maxItems: Int = 200): YtPlaylist {
        ensureInit()
        try {
            val info = PlaylistInfo.getInfo(ServiceList.YouTube, url)
            val items = ArrayList<YtPlaylistItem>()
            fun add(list: List<org.schabi.newpipe.extractor.stream.StreamInfoItem>) {
                list.forEach { item ->
                    val link = YoutubeUrls.parse(item.url) as? YtLink.Video ?: return@forEach
                    items += YtPlaylistItem(link.id, item.name.orEmpty(), item.uploaderName.orEmpty(), item.duration)
                }
            }
            add(info.relatedItems)
            var page: Page? = info.nextPage
            var pages = 1
            while (page != null && items.size < maxItems && pages < MAX_PLAYLIST_PAGES) {
                val next = PlaylistInfo.getMoreItems(ServiceList.YouTube, url, page)
                add(next.items)
                page = next.nextPage
                pages++
            }
            return YtPlaylist(info.name.orEmpty(), items.take(maxItems), truncated = items.size > maxItems || page != null)
        } catch (e: Exception) {
            DiagnosticLog.log("Resolver", "Playlist failed for $url", e)
            throw YoutubeException(e.message ?: e.javaClass.simpleName, e)
        }
    }

    // ---- Stream picking -----------------------------------------------------------------

    private const val AUTO_MAX_HEIGHT = 1080
    private val codecPreference = listOf("avc", "vp9", "av1", "hevc", "other")

    private val decoderMimes: Set<String> by lazy {
        try {
            MediaCodecList(MediaCodecList.REGULAR_CODECS).codecInfos
                .filter { !it.isEncoder }.flatMap { it.supportedTypes.toList() }.map { it.lowercase() }.toSet()
        } catch (_: Exception) { emptySet() }
    }

    private fun decodable(stream: YtVideoStream): Boolean {
        val mime = when (stream.family) {
            "avc" -> "video/avc"
            "vp9" -> "video/x-vnd.on2.vp9"
            "av1" -> "video/av01"
            "hevc" -> "video/hevc"
            else -> return true
        }
        return decoderMimes.isEmpty() || mime in decoderMimes
    }

    fun availableHeights(video: YtVideo): List<Int> =
        (video.videoOnly + video.muxed).filter { decodable(it) && it.height > 0 }.map { it.height }.distinct().sortedDescending()

    /** Best stream for [height] (0 = auto, capped at 1080p), preferring widely supported codecs. */
    fun pickVideo(video: YtVideo, height: Int): YtVideoStream? {
        val usable = video.videoOnly.filter { decodable(it) && it.height > 0 }
        val target = if (height > 0) height else {
            usable.map { it.height }.filter { it <= AUTO_MAX_HEIGHT }.maxOrNull() ?: usable.maxOfOrNull { it.height } ?: 0
        }
        val atHeight = usable.filter { it.height == target }
        val choice = atHeight.sortedWith(
            compareBy<YtVideoStream> { codecPreference.indexOf(it.family).let { i -> if (i < 0) 99 else i } }
                .thenByDescending { it.fps }.thenByDescending { it.bitrate },
        ).firstOrNull()
        return choice ?: usable.minByOrNull { kotlin.math.abs(it.height - target) }
    }

    fun pickMuxed(video: YtVideo, height: Int): YtVideoStream? =
        video.muxed.filter { decodable(it) }.let { list ->
            if (height > 0) list.minByOrNull { kotlin.math.abs(it.height - height) } else list.maxByOrNull { it.height }
        }

    /** One entry per distinct audio track (language/type), best bitrate each. */
    fun audioTracks(video: YtVideo): List<YtAudioStream> =
        video.audio.groupBy { it.trackId ?: "default" }
            .map { (_, group) -> group.maxByOrNull { it.bitrate }!! }
            .sortedWith(compareBy({ it.kind != AudioKind.ORIGINAL }, { it.label }))

    fun pickAudio(video: YtVideo, trackId: String?): YtAudioStream? {
        val tracks = audioTracks(video)
        if (tracks.isEmpty()) return null
        return tracks.firstOrNull { trackId != null && (it.trackId ?: "default") == trackId } ?: tracks.first()
    }
}
