package com.drishyopot.app.download

import com.drishyopot.app.yt.YoutubeResolver
import com.drishyopot.app.yt.YtAudioStream
import com.drishyopot.app.yt.YtVideo

/** What a resolved video offers, for the download dialog. */
object DownloadOptions {
    private val familyOrder = listOf("avc", "vp9", "av1", "hevc")

    fun heights(video: YtVideo): List<Int> =
        video.videoOnly.map { it.height }.filter { it > 0 }.distinct().sortedDescending()

    fun families(video: YtVideo, height: Int): List<String> =
        video.videoOnly.filter { it.height == height }.map { it.family }.distinct()
            .sortedBy { familyOrder.indexOf(it).let { i -> if (i < 0) 99 else i } }

    fun audioTracks(video: YtVideo): List<YtAudioStream> = YoutubeResolver.audioTracks(video)

    /** One entry per language: (language tag, label), manual captions preferred over automatic. */
    fun subtitleLanguages(video: YtVideo): List<Pair<String, String>> =
        video.subtitles.groupBy { it.language }
            .map { (lang, list) -> lang to (list.firstOrNull { !it.autoGenerated } ?: list.first()).label }
            .sortedBy { it.second }

    fun familyLabel(family: String) = when (family) {
        "avc" -> "H.264"
        "vp9" -> "VP9"
        "av1" -> "AV1"
        "hevc" -> "H.265"
        else -> family.uppercase()
    }

    /** Rough size from the streams' bitrates; 0 when unknown. */
    fun estimateBytes(video: YtVideo, mode: DlMode, height: Int, family: String, audioTrackId: String?): Long {
        val seconds = video.durationMs / 1000
        val audio = YoutubeResolver.pickAudio(video, audioTrackId)?.bitrate ?: 0
        val videoBitrate = if (mode == DlMode.VIDEO) {
            video.videoOnly.filter { it.height == height && (family.isBlank() || it.family == family) }.maxOfOrNull { it.bitrate } ?: 0
        } else 0
        return (videoBitrate + audio).toLong() / 8 * seconds
    }

    fun formatSize(bytes: Long): String = when {
        bytes <= 0 -> "—"
        bytes >= 1_000_000_000 -> "%.2f GB".format(bytes / 1_000_000_000.0)
        bytes >= 1_000_000 -> "%.1f MB".format(bytes / 1_000_000.0)
        else -> "%d KB".format(bytes / 1000)
    }

    fun formatEta(seconds: Long): String = when {
        seconds < 0 -> "—"
        seconds >= 3600 -> "%d:%02d:%02d".format(seconds / 3600, (seconds % 3600) / 60, seconds % 60)
        else -> "%d:%02d".format(seconds / 60, seconds % 60)
    }

    fun formatSpeed(bps: Long): String = when {
        bps >= 1_000_000 -> "%.1f MB/s".format(bps / 1_000_000.0)
        bps >= 1000 -> "%d KB/s".format(bps / 1000)
        else -> "$bps B/s"
    }
}
